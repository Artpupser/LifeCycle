test("1.6 recurring events preserve Markdown, reach Today/calendar, and create editable local greetings on mobile", async ({ page, request }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await login(page, request);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/countdowns");
  await page.getByRole("button", { name: "Новое событие", exact: true }).click();
  await page.getByLabel("Название события", { exact: true }).fill("Памятная дата 1.6");
  await chooseChoice(page.getByLabel("Категория события", { exact: true }), "personal");
  await chooseChoice(page.getByLabel("Повторение события", { exact: true }), "daily");
  await page.getByLabel("Описание события", { exact: true }).fill("**Событие Markdown**\n\n<script>alert(1)</script>");
  await page.getByRole("button", { name: "Сохранить событие", exact: true }).click();
  const card = page.locator("article").filter({ has: page.getByRole("heading", { name: "Памятная дата 1.6", exact: true }) });
  await card.getByText("Подробности",{exact:true}).click();
  await expect(card.locator("strong")).toHaveText("Событие Markdown");
  await expect(card).toContainText("Ежедневно"); await page.reload();
  await chooseAction(page,"Поздравление",card);
  await expect(page.getByLabel("Получатель поздравления", { exact: true })).toHaveValue("");
  await page.getByLabel("Получатель поздравления", { exact: true }).fill("Анна");
  await chooseChoice(page.getByLabel("Стиль поздравления", { exact: true }), "family");
  await page.getByRole("button", { name: "Создать по шаблону", exact: true }).click();
  await expect(page.getByLabel("Текст поздравления", { exact: true })).toHaveValue(/Анна, С любовью/);
  await page.getByLabel("Текст поздравления", { exact: true }).fill("Моё поздравление");
  await page.getByRole("dialog").getByRole("button", { name: "Закрыть окно", exact: true }).click();
  await page.goto("/today");
  await expect(page.getByRole("region", { name: "События дня", exact: true })).toContainText("Памятная дата 1.6");
  await page.goto("/calendar");
  await expect(page.getByRole("region", { name: "План выбранного дня", exact: true })).toContainText("Памятная дата 1.6");
  await page.goto("/countdowns");
  await expect.poll(() => page.locator("aside").evaluate(e => Math.round(e.getBoundingClientRect().width))).toBe(64);
  expect(await page.locator("html").evaluate(e => e.scrollWidth)).toBeLessThanOrEqual(390);
  expect(await page.locator(".app-content").evaluate(e => e.scrollWidth - e.clientWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: info.outputPath("events-mobile.png"), fullPage: true });
  expect(errors).toEqual([]);
});

test("1.7 Pomodoro constructor, snapshots, pause/reload/reset, copying and automatic history work", async ({ page, request }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await login(page, request); await page.goto("/pomodoro");
  await page.getByRole("button", { name: "Новый алгоритм", exact: true }).click();
  await page.getByLabel("Название алгоритма", { exact: true }).fill("Мой алгоритм");
  await page.getByLabel("Работа, секунд", { exact: true }).fill("30");
  await page.getByLabel("Обычный отдых, секунд", { exact: true }).fill("10");
  await page.getByLabel("Продолжительный отдых, секунд", { exact: true }).fill("10");
  await page.getByRole("button", { name: "+ Работа", exact: true }).click();
  await page.getByRole("button", { name: "Удалить интервал 5", exact: true }).click();
  await page.getByRole("button", { name: "Интервал 2 вниз", exact: true }).click();
  await expectChoiceValue(page.getByLabel("Тип интервала 2", { exact: true }), "w");
  await page.getByLabel("Повторять всю последовательность", { exact: true }).uncheck();
  await page.getByRole("button", { name: "Сохранить алгоритм", exact: true }).click();
  await page.reload();
  await chooseAction(page,"Запустить Мой алгоритм");
  await expect(page.getByText("Далее: Работа 30 сек.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Пауза", exact: true }).click();
  const paused = await page.getByRole("timer").textContent(); await page.reload();
  await expect(page.getByRole("button", { name: "Продолжить", exact: true })).toBeVisible();
  await expect(page.getByRole("timer")).toHaveText(paused!);
  await page.getByRole("button", { name: "Сбросить", exact: true }).click();
  await expect(page.getByRole("timer")).toHaveText("00:30");
  await page.getByRole("button", { name: "Остановить", exact: true }).click();
  await chooseAction(page,"Копировать алгоритм Мой алгоритм");
  await page.getByLabel("Название алгоритма", { exact: true }).fill("Короткий алгоритм");
  for (const label of ["Работа, секунд", "Обычный отдых, секунд", "Продолжительный отдых, секунд"]) await page.getByLabel(label, { exact: true }).fill("1");
  await page.getByRole("button", { name: "Сохранить алгоритм", exact: true }).click();
  await chooseAction(page,"Запустить Короткий алгоритм");
  await expect(page.getByText("Алгоритм завершён. История сохранена.", { exact: true })).toBeVisible({ timeout: 12000 });
  const history = page.getByRole("region", { name: "История Pomodoro", exact: true });
  await expect(history).toContainText("Работа · Завершён");
  await expect(history).toContainText("Продолжительный отдых · Завершён");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator("aside").evaluate(e => Math.round(e.getBoundingClientRect().width))).toBe(64);
  expect(await page.locator("html").evaluate(e => e.scrollWidth)).toBeLessThanOrEqual(390);
  expect(await page.locator(".app-content").evaluate(e => e.scrollWidth - e.clientWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: info.outputPath("pomodoro-mobile.png"), fullPage: true });
  expect(errors).toEqual([]);
});

