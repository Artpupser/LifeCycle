import { expect, test, type Page, type APIRequestContext } from "@playwright/test";

async function login(page: Page, request: APIRequestContext) {
  const email = `analytics-${Date.now()}-${Math.random().toString(16).slice(2)}@example.test`;
  const mailpit = process.env.MAILPIT_URL ?? "http://localhost:8025";
  await page.goto("/analytics");
  await expect(page.getByRole("heading", { name: "Войти или создать аккаунт" })).toBeVisible();
  await page.getByLabel("Электронная почта", { exact: true }).fill(email);
  await page.getByRole("button", { name: "Получить код", exact: true }).click();
  let code = "";
  await expect.poll(async () => {
    const inbox = await (await request.get(`${mailpit}/api/v1/messages`)).json();
    const message = inbox.messages.find((item: { To: { Address: string }[] }) => item.To.some((to) => to.Address === email));
    if (!message) return false;
    const detail = await (await request.get(`${mailpit}/api/v1/message/${message.ID}`)).json();
    code = detail.Text.match(/\b\d{6}\b/)?.[0] ?? "";
    return code.length === 6;
  }, { timeout: 20_000 }).toBe(true);
  await page.getByLabel("Код подтверждения").fill(code);
  await page.getByRole("button", { name: "Продолжить", exact: true }).click();
  await expect(page.getByRole("button", { name: "Выйти", exact: true })).toBeVisible();
}

test("mobile analytics uses real outcomes, explicit private summaries, revocation and date filters", async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const failures: string[] = []; page.on("pageerror", (e) => failures.push(e.message));
  await login(page, request);
  const today = new Date().toISOString().slice(0, 10);
  const yesterday = new Date(Date.now() - 86_400_000).toISOString().slice(0, 10);
  const origin = new URL(page.url()).origin;
  const write = async (method: "POST" | "PUT" | "DELETE", path: string, data?: unknown) => {
    const response = await page.request.fetch(`/api${path}`, { method, headers: { Origin: origin }, ...(data === undefined ? {} : { data }) });
    expect(response.ok()).toBe(true);
    return response.status() === 204 ? null : response.json();
  };
  const rule = { start_date: yesterday, time: null, timezone: "UTC", duration_minutes: 15, recurrence: "daily", interval_days: 1, weekdays: [], end_date: null };
  const task = await write("POST", "/tasks", { title: "Итог для аналитики", description: "**Личный текст**", schedule: rule });
  await write("POST", `/tasks/${task.id}/occurrences/${yesterday}`, { status: "completed" });
  const habit = await write("POST", "/habits", { title: "Ритм аналитики", schedule: rule });
  await write("POST", `/habits/${habit.id}/marks/${yesterday}`, { status: "completed" });
  await write("POST", `/habits/${habit.id}/marks/${today}`, { status: "skipped" });
  await write("PUT", "/profile", { name: "Закрытое имя", height_cm: 180, weight_kg: 75, conditions: ["Закрытый диагноз"] });
  await write("POST", "/sex", { kind: "masturbation", local_start: `${yesterday}T12:30:00`, timezone: "UTC", duration_minutes: 20, note: "Закрытая заметка" });
  await page.getByRole("link", { name: "Аналитика", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Аналитика", exact: true })).toBeVisible();
  const profile = page.getByLabel("Разрешить показатели профиля: возраст, рост и вес", { exact: true });
  const intimacy = page.getByLabel("Разрешить интимную сводку: количества и длительность", { exact: true });
  await expect(profile).not.toBeChecked(); await expect(intimacy).not.toBeChecked();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toContainText("Выполнено1");
  await expect(page.getByRole("region", { name: "Привычки", exact: true })).toContainText("50%");
  const report = await (await page.request.get(`/api/analytics?from=${yesterday}&to=${today}`)).json();
  expect(report.profile).toBeUndefined(); expect(report.intimacy).toBeUndefined();
  await expect(page.getByRole("region", { name: "Показатели профиля", exact: true })).toHaveCount(0);
  await profile.check();
  await expect(page.getByRole("region", { name: "Показатели профиля", exact: true })).toContainText("180");
  await intimacy.check();
  await expect(page.getByRole("region", { name: "Интимная сводка", exact: true })).toContainText("Известная длительность, мин20");
  await expect(page.locator("main")).not.toContainText("Закрытое имя");
  await expect(page.locator("main")).not.toContainText("Закрытый диагноз");
  await expect(page.locator("main")).not.toContainText("Закрытая заметка");
  const chart = page.getByRole("region", { name: "Динамика по дням", exact: true });
  await chart.getByRole("button", { name: "Задачи", exact: true }).click();
  await chart.getByRole("button", { name: `${yesterday}: 1`, exact: true }).click();
  await expect(chart.getByText(/Задачи: 1/)).toBeVisible();
  expect(await page.locator("html").evaluate((e) => e.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath("mobile-analytics.png"), fullPage: true });
  await profile.uncheck();
  await expect(page.getByRole("region", { name: "Показатели профиля", exact: true })).toHaveCount(0);
  await intimacy.uncheck();
  await expect(page.getByRole("region", { name: "Интимная сводка", exact: true })).toHaveCount(0);
  await page.reload(); await expect(profile).not.toBeChecked(); await expect(intimacy).not.toBeChecked();
  const revoked = await (await page.request.get(`/api/analytics?from=${yesterday}&to=${today}`)).json();
  expect(revoked.profile).toBeUndefined(); expect(revoked.intimacy).toBeUndefined();
  await page.getByLabel("Период с", { exact: true }).fill("2020-01-01");
  await page.getByRole("button", { name: "Применить период", exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await page.getByRole("button", { name: "7 дн.", exact: true }).click();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "1. Ритм аналитики", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("heading", { name: "🌱 Ритм аналитики", exact: true })).toBeVisible();
  await expect(page.getByRole("dialog").getByRole("link", { name: "Открыть Today", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Закрыть окно", exact: true }).click();
  await page.getByRole("link", { name: "Аналитика", exact: true }).click();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toBeVisible();
  await write("DELETE", `/tasks/${task.id}`); await write("DELETE", `/habits/${habit.id}`);
  await page.getByRole("button", { name: "Обновить аналитику", exact: true }).click();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toContainText("Выполнено1");
  await page.getByRole("link", { name: "1. Ритм аналитики", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("Ритм аналитики");
  await expect(page.getByRole("dialog").getByLabel("Результат Ритм аналитики", { exact: true }).first()).toBeDisabled();
  await page.getByRole("button", { name: "Закрыть окно", exact: true }).click();
  await page.getByRole("link", { name: "Аналитика", exact: true }).click();
  await page.getByRole("button", { name: "Скрыть аналитику", exact: true }).click();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Показать аналитику", exact: true }).click();
  await expect(page.getByRole("region", { name: "Задачи", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Выйти", exact: true }).click();
  await page.goto("/analytics");
  await expect(page.getByRole("heading", { name: "Войти или создать аккаунт" })).toBeVisible();
  expect(failures).toEqual([]);
});
