test("timed workout checks actual expiry, round rests and cancellation after reload", async ({ page, request }) => {
  await login(page, request);
  await page.getByRole("link", { name: "Тренировки", exact: true }).click();
  await page.getByRole("button", { name: "Новое упражнение", exact: true }).click();
  await page.getByLabel("Название упражнения", { exact: true }).fill("Планка браузера");
  await page.getByLabel("Тип упражнения", { exact: true }).selectOption("duration");
  await page.getByRole("button", { name: "Сохранить упражнение", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Новая тренировка", exact: true }).click();
  await page.getByLabel("Название тренировки", { exact: true }).fill("Временная тренировка");
  await page.getByLabel("Повторов круга", { exact: true }).fill("2");
  await page.getByLabel("Отдых после круга, сек", { exact: true }).fill("1");
  await page.getByRole("button", { name: "Добавить упражнение", exact: true }).click();
  await page.getByLabel("Начальное время, сек", { exact: true }).fill("3");
  await page.getByRole("button", { name: "Сохранить тренировку", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Начать тренировку", exact: true }).click();
  await expect(page.getByRole("button", { name: "Упражнение выполнено", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Пауза", exact: true }).click();
  await expect(page.getByRole("button", { name: "Продолжить", exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Продолжить", exact: true }).click();
  await expect(page.getByRole("button", { name: "Упражнение выполнено", exact: true })).toBeEnabled({ timeout: 10000 });
  await page.getByRole("button", { name: "Упражнение выполнено", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Отдых", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Завершить отдых", exact: true })).toBeEnabled({ timeout: 5000 });
  await page.getByRole("button", { name: "Завершить отдых", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Планка браузера", exact: true })).toBeVisible();
  page.once("dialog", (dialog) => void dialog.accept());
  await page.getByRole("button", { name: "Остановить тренировку", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Остановлено", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "1. Планка браузера", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Остановлено", exact: true })).toBeVisible();
});
