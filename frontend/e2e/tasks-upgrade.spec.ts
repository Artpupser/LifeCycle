async function createBoard(page: Page, name: string) {
  await page.goto("/tasks");
  await page.getByRole("button", { name: "Новая доска", exact: true }).click();
  await page.getByLabel("Название доски", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Сохранить доску", exact: true }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
}
async function boardMenu(page: Page) { await page.getByLabel("Действия доски", { exact: true }).click(); }

