import { expect, test } from "@playwright/test";

test("mobile AI uses independent grants, exact previews, private key lifecycle and explicit deletion", async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  await page.goto("/ai");
  await expect(page.getByRole("heading", { name: "Войти или создать аккаунт" })).toBeVisible();
  const origin = new URL(page.url()).origin;
  const email = `ai-${Date.now()}-${Math.random().toString(16).slice(2)}@example.test`;
  const mailpit = process.env.MAILPIT_URL ?? "http://localhost:8025";
  expect((await page.request.post("/api/auth/request-code", { headers: { Origin: origin }, data: { email } })).status()).toBe(202);
  let code = "";
  await expect.poll(async () => {
    const inbox = await (await request.get(`${mailpit}/api/v1/messages`)).json();
    const message = inbox.messages.find((item: { To: { Address: string }[] }) => item.To.some((to) => to.Address === email));
    if (!message) return false;
    const detail = await (await request.get(`${mailpit}/api/v1/message/${message.ID}`)).json();
    code = detail.Text.match(/\b\d{6}\b/)?.[0] ?? "";
    return code.length === 6;
  }, { timeout: 20_000 }).toBe(true);
  expect((await page.request.post("/api/auth/verify-code", { headers: { Origin: origin }, data: { email, code } })).ok()).toBe(true);
  const write = async (method: "POST" | "PUT" | "DELETE", path: string, data?: unknown) => {
    const response = await page.request.fetch(`/api${path}`, { method, headers: { Origin: origin }, ...(data === undefined ? {} : { data }) });
    expect(response.ok()).toBe(true);
    return response.status() === 204 ? null : response.json();
  };
  const marker = "Закрытый текст для проверки AI";
  const note = await write("POST", "/notes", { title: "Заметка для AI", content: `**${marker}**\n<script>throw new Error('injected')</script>` });
  await write("PUT", "/profile", { name: marker, conditions: [marker] });
  await write("PUT", "/analytics/privacy", { include_profile: true, include_intimacy: true });
  await page.goto("/ai");
  await expect(page.getByRole("heading", { name: "AI-помощник", exact: true })).toBeVisible();
  await expect(page.getByRole("checkbox", { checked: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Новый чат", exact: true }).click();
  await page.getByLabel("Ваше сообщение", { exact: true }).fill("Объясни мои результаты.");
  await page.getByRole("button", { name: "Подготовить предпросмотр", exact: true }).click();
  const preview = page.getByRole("region", { name: "Предпросмотр отправки", exact: true });
  await expect(preview).toBeVisible();
  await preview.getByText("Точный запрос OpenAI", { exact: true }).click();
  await expect(preview.locator("pre")).not.toContainText(marker);
  await expect(preview.getByRole("button", { name: "Отправить в OpenAI" })).toBeDisabled();
  const notes = page.getByRole("checkbox", { name: /^Тексты заметок/ });
  await notes.check();
  await expect(page.getByLabel("Ваше сообщение", { exact: true })).toBeEnabled();
  await page.getByLabel("Ваше сообщение", { exact: true }).fill("Черновик при изменении настроек");
  await expect(page.getByLabel("Ваше сообщение", { exact: true })).toHaveValue("Черновик при изменении настроек");
  await expect(page.getByRole("button", { name: "Подготовить предпросмотр", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Сохранить настройки AI", exact: true }).click();
  await expect(notes).toBeChecked();
  await expect(page.getByLabel("Ваше сообщение", { exact: true })).toHaveValue("Черновик при изменении настроек");
  await page.getByLabel("Ваше сообщение", { exact: true }).fill("Как организовать заметки?");
  await page.getByRole("button", { name: "Подготовить предпросмотр", exact: true }).click();
  await preview.getByText("Точный запрос OpenAI", { exact: true }).click();
  await expect(preview.locator("pre")).toContainText(marker);
  expect(await page.locator("html").evaluate((element) => element.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath("mobile-ai.png"), fullPage: true });
  await page.getByRole("button", { name: "Отозвать доступ к данным", exact: true }).click();
  await expect(notes).not.toBeChecked();
  await page.getByLabel("Ваше сообщение", { exact: true }).fill("Вопрос после отзыва.");
  await page.getByRole("button", { name: "Подготовить предпросмотр", exact: true }).click();
  await preview.getByText("Точный запрос OpenAI", { exact: true }).click();
  await expect(preview.locator("pre")).not.toContainText(marker);
  await page.getByLabel("API-ключ OpenAI", { exact: true }).fill("sk-invalid-browser-check-123456789");
  await page.getByRole("button", { name: "Сохранить настройки AI", exact: true }).click();
  await expect(page.getByRole("button", { name: "Удалить API-ключ", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("API-ключ OpenAI", { exact: true })).toHaveValue("");
  await expect(page.getByRole("checkbox", { checked: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Удалить API-ключ", exact: true }).click();
  await expect(page.getByRole("button", { name: "Удалить API-ключ", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Удалить чат", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Отмена", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Переписка", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Удалить чат", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Удалить навсегда", exact: true }).click();
  await expect(page.getByRole("button", { name: "Удалить чат", exact: true })).toHaveCount(0);
  expect((await page.request.get(`/api/notes/${note.id}`)).ok()).toBe(true);
  await page.getByRole("button", { name: "Скрыть AI", exact: true }).click();
  await expect(page.getByLabel("API-ключ OpenAI", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Показать AI", exact: true }).click();
  await expect(page.getByLabel("API-ключ OpenAI", { exact: true })).toBeVisible();
  await page.getByLabel("Провайдер AI", { exact: true }).selectOption("openrouter");
  await page.getByLabel("API-ключ OpenRouter", { exact: true }).fill("sk-or-browser-synthetic-123456789");
  await page.getByRole("button", { name: "Сохранить настройки AI", exact: true }).click();
  await expect(page.getByLabel("Модель OpenRouter", { exact: true })).toHaveValue("openai/gpt-4.1-mini");
  await page.reload();
  await expect(page.getByLabel("Провайдер AI", { exact: true })).toHaveValue("openrouter");
  await expect(page.getByLabel("API-ключ OpenRouter", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Удалить API-ключ", exact: true }).click();
  await expect(page.getByRole("button", { name: "Удалить API-ключ", exact: true })).toHaveCount(0);
  await page.getByLabel("Провайдер AI", { exact: true }).selectOption("openai");
  await page.getByLabel("Способ подключения", { exact: true }).selectOption("login");
  await page.getByRole("button", { name: "Сохранить настройки AI", exact: true }).click();
  await expect(page.getByRole("button", { name: "Continue with ChatGPT", exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByLabel("Способ подключения", { exact: true })).toHaveValue("login");
  await expect(page.getByLabel("API-ключ OpenAI", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Новый чат", exact: true }).click();
  await page.getByLabel("Шаблон вопроса", { exact: true }).selectOption("План дня");
  await expect(page.getByLabel("Ваше сообщение", { exact: true })).toHaveValue(/реалистичный план дня/);
  await page.getByRole("button", { name: "Подготовить предпросмотр", exact: true }).click();
  await preview.getByText("Точный запрос OpenAI", { exact: true }).click();
  await expect(preview.locator("pre")).toContainText('"stream": true');
  await expect(preview.locator("pre")).not.toContainText('"max_output_tokens"');
  await expect(preview.getByRole("button", { name: "Отправить в OpenAI" })).toBeDisabled();
  expect(await page.locator("html").evaluate((element) => element.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath("mobile-ai-connections.png"), fullPage: true });
  await page.goto("/settings");
  await expect(page.getByRole("heading", { name: "Настройки", exact: true })).toBeVisible();
  await page.getByRole("checkbox", { name: /^Тексты заметок/ }).check();
  await page.getByRole("button", { name: "Сохранить настройки AI", exact: true }).click();
  await page.goto("/ai");
  await expect(page.getByRole("checkbox", { name: /^Тексты заметок/ })).toBeChecked();
  await page.getByRole("button", { name: "Отозвать доступ к данным", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: /^Тексты заметок/ })).not.toBeChecked();
  await write("DELETE", `/notes/${note.id}`);
  expect(failures).toEqual([]);
});
