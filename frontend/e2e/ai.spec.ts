import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";

test("AI is a one-click chat with per-item sharing, automatic replies and safe revocation", async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  await page.goto("/ai");
  const origin = new URL(page.url()).origin;
  const email = `ai-upgrade-${randomUUID()}@example.test`;
  expect((await page.request.post("/api/auth/request-code", { headers: { Origin: origin }, data: { email } })).status()).toBe(202);
  let code = "";
  const mailpit = process.env.MAILPIT_URL ?? "http://localhost:8025";
  await expect.poll(async () => {
    const inbox = await (await request.get(`${mailpit}/api/v1/search`, { params: { query: `to:${email}` } })).json();
    const message = inbox.messages.find((item: { To: { Address: string }[] }) => item.To.some((to) => to.Address === email));
    if (!message) return false;
    const detail = await (await request.get(`${mailpit}/api/v1/message/${message.ID}`)).json();
    code = detail.Text.match(/\b\d{6}\b/)?.[0] ?? "";
    return code.length === 6;
  }).toBe(true);
  const identity = await (await page.request.post("/api/auth/verify-code", { headers: { Origin: origin }, data: { email, code } })).json();
  async function write(path: string, data?: unknown, method = "POST") {
    const response = await page.request.fetch(`/api${path}`, { method, headers: { Origin: origin }, ...(data === undefined ? {} : { data }) });
    expect(response.ok()).toBe(true);
    return response.status() === 204 ? null : response.json();
  }
  const note = await write("/notes", { title: "Выбранная заметка", content: "**SHARED_NOTE_MARKER**" });
  const privateNote = await write("/notes", { title: "PRIVATE_NOTE_MARKER", content: "Не передавать" });
  const exercise = await write("/exercises", { title: "EXERCISE_MARKER", kind: "repetitions", description: "**Техника**" });
  const privateExercise = await write("/exercises", { title: "PRIVATE_EXERCISE_MARKER", kind: "repetitions" });
  function plan(title: string, exerciseId: string) { return { title, description: "**План**", tags: [], rounds: [{ id: randomUUID(), title: "Круг", repeat: 1, rest_seconds: 0, exercises: [{ id: randomUUID(), exercise_id: exerciseId, repetitions: 10, duration_seconds: 0, rest_seconds: 0, progression: null }] }] }; }
  const workout = await write("/workouts", plan("Выбранная тренировка", exercise.id));
  const privateWorkout = await write("/workouts", plan("PRIVATE_WORKOUT_MARKER", privateExercise.id));
  expect(note.ai_shared).toBe(false); expect(workout.ai_shared).toBe(false); expect(exercise.ai_shared).toBe(false);
  await page.goto("/notes");
  await page.getByRole("checkbox", { name: "AI Доступ: Выбранная заметка", exact: true }).check();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: Выбранная заметка", exact: true })).toBeEnabled();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: PRIVATE_NOTE_MARKER", exact: true })).not.toBeChecked();
  await page.reload();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: Выбранная заметка", exact: true })).toBeChecked();
  await page.goto("/workouts");
  await page.getByRole("checkbox", { name: "AI Доступ: Выбранная тренировка", exact: true }).check();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: Выбранная тренировка", exact: true })).toBeEnabled();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: PRIVATE_WORKOUT_MARKER", exact: true })).not.toBeChecked();
  await page.getByRole("checkbox", { name: "AI Доступ: EXERCISE_MARKER", exact: true }).check();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: EXERCISE_MARKER", exact: true })).toBeEnabled();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: PRIVATE_EXERCISE_MARKER", exact: true })).not.toBeChecked();
  // A shared library exercise is useful before any plan exists.
  const standalone = await write("/exercises", { title: "STANDALONE_EXERCISE_MARKER", kind: "duration" });
  await page.reload();
  await page.getByRole("checkbox", { name: "AI Доступ: STANDALONE_EXERCISE_MARKER", exact: true }).check();
  await expect(page.getByRole("checkbox", { name: "AI Доступ: STANDALONE_EXERCISE_MARKER", exact: true })).toBeEnabled();
  await page.getByLabel("Цели тренировок", { exact: true }).fill("GOALS_MARKER · выносливость");
  await page.getByLabel("Оборудование", { exact: true }).fill("EQUIPMENT_MARKER · коврик");
  await page.getByLabel("Ограничения", { exact: true }).fill("RESTRICTIONS_MARKER · без прыжков");
  await page.getByRole("button", { name: "Сохранить цели и условия", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Цели и условия сохранены.");
  await page.reload();
  await expect(page.getByLabel("Цели тренировок", { exact: true })).toHaveValue("GOALS_MARKER · выносливость");
  await expect(page.getByLabel("Оборудование", { exact: true })).toHaveValue("EQUIPMENT_MARKER · коврик");
  await expect(page.getByLabel("Ограничения", { exact: true })).toHaveValue("RESTRICTIONS_MARKER · без прыжков");
  await expect(page.getByRole("checkbox", { name: "AI Доступ: STANDALONE_EXERCISE_MARKER", exact: true })).toBeChecked();
  await page.getByRole("region", { name: "Условия тренировок", exact: true }).screenshot({ path: testInfo.outputPath("mobile-training-conditions.png") });
  expect(await page.locator("html").evaluate((el) => el.scrollWidth)).toBeLessThanOrEqual(390);
  let config = await (await page.request.get("/api/ai/settings")).json();
  config = await write("/ai/settings", { revision: config.revision, model: config.model, enabled: true, api_key: "sk-synthetic-ui-only-never-sent-123456", permissions: { ...config.permissions, notes: true, workouts: true, changes: true } }, "PUT");
  let posted = 0;
  let exactRequest: unknown;
  let revision = config.revision;
  // Keep real create-chat/preview/history and DB encryption; only substitute inference.
  await page.route(/\/api\/ai\/chats\/[^/]+\/preview$/, async (route) => {
    const response = await route.fetch();
    const data = await response.json();
    if (response.ok()) { exactRequest = data.request; revision = data.config_revision; }
    await route.fulfill({ response });
  });
  await page.route(/\/api\/ai\/chats\/[^/]+\/messages$/, async (route) => {
    posted++;
    const body = route.request().postDataJSON();
    const chat = new URL(route.request().url()).pathname.split("/")[4]!;
    execFileSync("python3", ["../scripts/ai_test_fixture.py"], { input: JSON.stringify({ user: identity.user.id, chat, turn: body.request_id, revision, request: exactRequest, answer: `**Ответ ${posted} готов**. SHARED_NOTE_MARKER` }) });
    await route.fulfill({ status: 202, contentType: "application/json", body: JSON.stringify({ id: body.request_id, status: "completed" }) });
  });
  await page.goto("/ai");
  await expect(page.getByRole("heading", { name: "Чем займёмся сегодня?" })).toBeVisible();
  await expect(page.getByText("Цели и персонализация", { exact: true })).toHaveCount(0);
  await expect(page.getByLabel(/Поиск в разрешённых/)).toHaveCount(0);
  const question = page.getByLabel("Ваше сообщение", { exact: true });
  await page.getByRole("button", { name: "Создать тренировку", exact: true }).click();
  await expect(question).toHaveValue(/из раздела «Тренировки»/);
  await page.getByRole("button", { name: "Отправить", exact: true }).click();
  await expect(page.getByText("Ответ 1 готов", { exact: true })).toBeVisible();
  expect(posted).toBe(1);
  expect(JSON.stringify(exactRequest)).toContain("SHARED_NOTE_MARKER");
  expect(JSON.stringify(exactRequest)).toContain("Выбранная тренировка");
  expect(JSON.stringify(exactRequest)).toContain("EXERCISE_MARKER");
  for (const marker of ["STANDALONE_EXERCISE_MARKER", "GOALS_MARKER", "EQUIPMENT_MARKER", "RESTRICTIONS_MARKER"]) expect(JSON.stringify(exactRequest)).toContain(marker);
  expect(JSON.stringify(exactRequest)).not.toContain("PRIVATE_");
  await expect(question).toHaveValue("");
  await expect(page.getByRole("button", { name: "Организация заметок", exact: true })).toBeVisible();
  await question.fill("Мой черновик.");
  await page.getByRole("button", { name: "Адаптировать нагрузку", exact: true }).click();
  await expect(question).toHaveValue(/^Мой черновик\.\n\nОцени фактические результаты/);
  await page.reload();
  await expect(page.getByRole("button", { name: "Создать тренировку", exact: true })).toBeVisible();
  await question.fill("Первая строка");
  await question.press("Shift+Enter");
  await question.pressSequentially("Вторая строка");
  expect(posted).toBe(1);
  await question.press("Enter");
  await expect(page.getByText("Ответ 2 готов", { exact: true })).toBeVisible();
  expect(posted).toBe(2);
  await question.fill("Вопрос после отзыва доступа.");
  await page.getByRole("button", { name: "Данные для отправки", exact: true }).click();
  await expect(page.getByRole("region", { name: "Предпросмотр отправки" })).toContainText("SHARED_NOTE_MARKER");
  await write(`/notes/${note.id}/ai-access`, { revision: 1, ai_shared: false }, "PUT");
  await page.evaluate("window.dispatchEvent(new Event('focus'))");
  await expect(page.getByRole("region", { name: "Предпросмотр отправки" })).toHaveCount(0);
  await expect(question).toHaveValue("Вопрос после отзыва доступа.");
  await page.getByRole("button", { name: "Данные для отправки", exact: true }).click();
  await expect(page.getByRole("region", { name: "Предпросмотр отправки" })).not.toContainText("SHARED_NOTE_MARKER");
  await page.getByRole("button", { name: "Настройки AI", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: /^Тренировки/ })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: /^Редактор тренировок/ })).toHaveCount(0);
  await page.getByRole("button", { name: "Удалить API-ключ", exact: true }).click();
  await expect(page.getByRole("button", { name: "Отправить", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Закрыть настройки AI", exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath("mobile-ai-chat.png"), fullPage: true });
  expect(await page.locator("html").evaluate((el) => el.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole("button", { name: "Удалить чат", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Отмена", exact: true }).click();
  await page.getByRole("button", { name: "Удалить чат", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Удалить навсегда", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Чем займёмся сегодня?" })).toBeVisible();
  expect((await page.request.get(`/api/notes/${note.id}`)).ok()).toBe(true);
  await write(`/notes/${privateNote.id}`, undefined, "DELETE");
  await write(`/workouts/${privateWorkout.id}`, undefined, "DELETE");
  await write(`/exercises/${standalone.id}`, undefined, "DELETE");
  expect(failures).toEqual([]);
});
