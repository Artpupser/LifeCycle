test("journal reports DST errors and preserves concurrent changes",async ({page,request}) => {
  await login(page,request);
  await page.getByRole("button",{name:"Новое событие",exact:true}).click();
  await page.getByLabel("Местное время начала",{exact:true}).fill("2026-03-29T02:30");
  await page.getByLabel("Часовой пояс события",{exact:true}).fill("Europe/Berlin");
  await page.getByRole("button",{name:"Сохранить событие",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("Такого местного времени нет");
  await page.getByLabel("Местное время начала",{exact:true}).fill("2026-10-25T02:30");
  await page.getByLabel("При повторе часа (DST)",{exact:true}).selectOption("later");
  await page.getByRole("button",{name:"Сохранить событие",exact:true}).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("heading",{name:"События (1)",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Редактировать",exact:true}).click();
  await expect(page.getByLabel("При повторе часа (DST)",{exact:true})).toHaveValue("later");
  const journal = await (await page.request.get("/api/sex?from=2026-10-25&to=2026-10-25")).json() as {entries:{id:string;revision:number;data:Record<string,unknown>;started_at:string}[]};
  const entry = journal.entries[0];
  expect(entry.started_at).toBe("2026-10-25T01:30:00Z");
  const response = await page.request.put(`/api/sex/${entry.id}`,{headers:{Origin:new URL(page.url()).origin},data:{revision:entry.revision,data:{...entry.data,duration_minutes:35}}});
  expect(response.status()).toBe(200);
  await page.getByLabel("Длительность, минут",{exact:true}).fill("15");
  await page.getByRole("button",{name:"Сохранить событие",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("Запись изменена в другом окне");
  await expect(page.getByLabel("Длительность, минут",{exact:true})).toHaveValue("15");
  await page.getByRole("button",{name:"Отмена",exact:true}).click();
  await page.getByRole("button",{name:"Редактировать",exact:true}).click();
  await expect(page.getByLabel("Длительность, минут",{exact:true})).toHaveValue("35");
  await page.getByRole("button",{name:"Отмена",exact:true}).click();
});
